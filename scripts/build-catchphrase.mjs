// Turns the landing-page catchphrase into one SVG path per letter (Sora 800),
// so the page can draw each outline with anime.js's createDrawable.
// Run: node scripts/build-catchphrase.mjs
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const PHRASE = ["do it fastr", "with taskr"];
const SIZE = 120;
const LINE_HEIGHT = 136;

const fontFile = readFileSync(new URL("../node_modules/@fontsource/sora/files/sora-latin-800-normal.woff", import.meta.url));
const font = opentype.parse(fontFile.buffer.slice(fontFile.byteOffset, fontFile.byteOffset + fontFile.byteLength));

const lines = PHRASE.map((text, index) => {
  const width = font.getAdvanceWidth(text, SIZE, { kerning: true });
  return { text, width, y: SIZE * 0.95 + index * LINE_HEIGHT };
});
const maxWidth = Math.ceil(Math.max(...lines.map((line) => line.width)));

const glyphs = [];
for (const [lineIndex, line] of lines.entries()) {
  const x0 = (maxWidth - line.width) / 2;
  const paths = font.getPaths(line.text, x0, line.y, SIZE, { kerning: true });
  [...line.text].forEach((char, i) => {
    const d = paths[i].toPathData(1);
    // Mark the word "taskr" so it can be highlighted.
    const accent = lineIndex === 1 && i >= line.text.indexOf("taskr");
    if (d) glyphs.push({ char, d, accent });
  });
}

const height = Math.ceil(lines.at(-1).y + SIZE * 0.3);
const out = `// Generated by scripts/build-catchphrase.mjs — do not edit by hand.
export const CATCHPHRASE_VIEWBOX = "0 0 ${maxWidth} ${height}";
export const CATCHPHRASE_GLYPHS = ${JSON.stringify(glyphs, null, 0)};
`;
writeFileSync(new URL("../src/components/landing/catchphrase.js", import.meta.url), out);
console.log(`${glyphs.length} glyphs, viewBox 0 0 ${maxWidth} ${height}`);
